#!/usr/bin/env bash
# backup.sh — snapshot everything before changing anything, and generate restore.sh.
#
#   tools/backup.sh            -> backup/<timestamp>/ (+ backup/latest symlink)
#
# Saves: package lists (all/enabled/disabled/system/user), getprop, all settings tables,
# dumpsys package, HOME claimers, the current default home, TV inputs, and a screenshot.
# restore.sh in that folder re-enables every package debloat.sh disables and puts the
# original home screen back; debloat.sh and set-launcher.sh append to it as they go.
set -eu
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
TV="$HERE/tv.sh"
TS="$(date +%Y%m%d-%H%M%S)"
BK="$ROOT/backup/$TS"
mkdir -p "$BK/screens"

save() { # file  command
  printf '  %-28s' "$1"; "$TV" shell "$2" > "$BK/$1" 2>/dev/null || true; wc -l < "$BK/$1" | tr -d ' ' | sed 's/$/ lines/'
}
echo "Backing up to $BK"
save device.txt           "getprop ro.product.manufacturer; getprop ro.product.brand; getprop ro.product.model; getprop ro.product.device; getprop ro.build.version.release; getprop ro.build.version.sdk; getprop ro.build.display.id"
save packages-all.txt     "pm list packages -f"
save packages-enabled.txt "pm list packages -e"
save packages-disabled.txt "pm list packages -d"
save packages-system.txt  "pm list packages -s"
save packages-user.txt    "pm list packages -3"
save getprop.txt          "getprop"
save settings-system.txt  "settings list system"
save settings-secure.txt  "settings list secure"
save settings-global.txt  "settings list global"
save dumpsys-package.txt  "dumpsys package"
save home-activities.txt  "cmd package query-activities -a android.intent.action.MAIN -c android.intent.category.HOME"
save current-home.txt     "cmd package resolve-activity --brief -a android.intent.action.MAIN -c android.intent.category.HOME"
save tv-inputs.txt        "dumpsys tv_input"
save features.txt         "pm list features"
"$TV" screenshot "$BK/screens/before.png" >/dev/null && echo "  screens/before.png"

ORIG_HOME="$(grep -E '^[A-Za-z0-9_.]+/' "$BK/current-home.txt" | tail -1 | tr -d '\r' || true)"
HOME_PKGS="$(grep -oE '[A-Za-z0-9_.]+/[A-Za-z0-9_.$]+' "$BK/home-activities.txt" | cut -d/ -f1 | sort -u | tr '\n' ' ' || true)"
: > "$BK/disabled-by-us.txt"

cat > "$BK/restore.sh" <<RS
#!/usr/bin/env bash
# restore.sh — generated by tools/backup.sh on $TS.
# Device: $(tr '\n' ' ' < "$BK/device.txt")
# Re-enables every package disabled by tools/debloat.sh / set-launcher.sh and restores the
# original home screen. Safe to run more than once. Needs the TV connected (tools/connect.sh).
set -u
HERE="\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
TV="\$HERE/../../tools/tv.sh"
ORIG_HOME='$ORIG_HOME'
HOME_PKGS='$HOME_PKGS'

echo "Re-enabling the original home screen apps: \$HOME_PKGS"
for p in \$HOME_PKGS; do "\$TV" shell "pm enable --user 0 \$p"; done
if [ -n "\$ORIG_HOME" ]; then
  echo "Restoring default home: \$ORIG_HOME"
  "\$TV" shell "cmd package set-home-activity --user 0 \$ORIG_HOME"
fi
echo "Re-enabling packages listed in disabled-by-us.txt"
while IFS= read -r p || [ -n "\$p" ]; do
  case "\$p" in ''|'#'*) continue;; esac
  "\$TV" shell "pm enable --user 0 \$p"
done < "\$HERE/disabled-by-us.txt"
"\$TV" key HOME >/dev/null
echo "Done. The TV is back to its stock home screen; your launcher stays installed but inactive."
echo "To remove it too:  \$TV shell 'pm uninstall net.cleanhome.launcher'"
RS
chmod +x "$BK/restore.sh"
ln -sfn "$TS" "$ROOT/backup/latest"
echo
echo "Original home: ${ORIG_HOME:-unknown}"
echo "HOME claimers: ${HOME_PKGS:-none}"
echo "Restore script: $BK/restore.sh"
echo "Next: python3 tools/classify.py backup/latest"
